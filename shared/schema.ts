import { pgTable, text, serial, integer, boolean, timestamp } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod";

// Studies table schema
export const studies = pgTable("studies", {
  id: serial("id").primaryKey(),
  title: text("title").notNull(),
  abstract: text("abstract").notNull(),
  authors: text("authors").notNull(),
  journal: text("journal").notNull(),
  publishDate: text("publish_date").notNull(),
  category: text("category").notNull(),
  methods: text("methods"),
  results: text("results"),
  conclusion: text("conclusion"),
  doi: text("doi"),
  pdfUrl: text("pdf_url"),
  citationUrl: text("citation_url"),
  peerReviewed: boolean("peer_reviewed").notNull().default(true),
  // Media fields
  imageUrl: text("image_url"),
  imageAlt: text("image_alt"),
  videoUrl: text("video_url"),
  audioUrl: text("audio_url"),
  // Automatically generated image information
  autoGeneratedImage: boolean("auto_generated_image").default(false),
  createdAt: timestamp("created_at").notNull().defaultNow(),
});

// Categories table schema
export const categories = pgTable("categories", {
  id: serial("id").primaryKey(),
  name: text("name").notNull().unique(),
  description: text("description").notNull(),
  icon: text("icon"),
  studyCount: integer("study_count").notNull().default(0),
  createdAt: timestamp("created_at").notNull().defaultNow(),
});

// Newsletter subscriptions table schema
export const newsletters = pgTable("newsletters", {
  id: serial("id").primaryKey(),
  email: text("email").notNull().unique(),
  createdAt: timestamp("created_at").notNull().defaultNow(),
});

// Contact form messages table schema
export const contactMessages = pgTable("contact_messages", {
  id: serial("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull(),
  message: text("message").notNull(),
  createdAt: timestamp("created_at").notNull().defaultNow(),
});

// Create insertion schemas and types
export const insertStudySchema = createInsertSchema(studies).omit({ id: true, createdAt: true });
export const insertCategorySchema = createInsertSchema(categories).omit({ id: true, createdAt: true });
export const insertNewsletterSchema = createInsertSchema(newsletters).omit({ id: true, createdAt: true });
export const insertContactSchema = createInsertSchema(contactMessages).omit({ id: true, createdAt: true });

// Types for insertion
export type InsertStudy = z.infer<typeof insertStudySchema>;
export type InsertCategory = z.infer<typeof insertCategorySchema>;
export type InsertNewsletter = z.infer<typeof insertNewsletterSchema>;
export type InsertContact = z.infer<typeof insertContactSchema>;

// Types for selection
export type Study = typeof studies.$inferSelect;
export type Category = typeof categories.$inferSelect;
export type Newsletter = typeof newsletters.$inferSelect;
